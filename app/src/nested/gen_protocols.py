"""The forwarder's protocol table (2026-10-12): for each interface of wayland.xml and the protocols in
protocols.txt, its wl_interface (wayland-scanner's private code; core ones from libwayland-client),
the version the forwarder knows, and which requests and events destroy the object.
    gen_protocols.py WAYLAND_XML PROTOCOLS_DIR PROTOCOLS_TXT OUT_CPP"""
import pathlib
import sys
import xml.etree.ElementTree as ET

wayland_xml, protocols_dir, protocols_txt, out = sys.argv[1:5]
files = [pathlib.Path(wayland_xml)]
for line in pathlib.Path(protocols_txt).read_text().splitlines():
    line = line.strip()
    if line and not line.startswith("#"):
        p = pathlib.Path(line)
        files.append(p if p.is_absolute() else pathlib.Path(protocols_dir) / p)

rows, externs = [], []
for f in files:
    core = f == files[0]
    for iface in ET.parse(f).getroot().iter("interface"):
        name = iface.get("name")
        version = int(iface.get("version", "1"))
        masks = []
        for kind in ("request", "event"):
            m = 0
            for i, msg in enumerate(iface.findall(kind)):
                if msg.get("type") == "destructor":
                    m |= 1 << i
            masks.append(m)
        rows.append(f'    {{"{name}", &{name}_interface, {version}, 0x{masks[0]:x}ull, 0x{masks[1]:x}ull}},')
        if not core:
            externs.append(f"extern const struct wl_interface {name}_interface;")

pathlib.Path(out).write_text(
    "// generated by gen_protocols.py\n"
    '#include "protocols.h"\n'
    "#include <wayland-client-protocol.h>\n\n"
    'extern "C" {\n' + "\n".join(externs) + "\n}\n\n"
    "const vmview_iface vmview_ifaces[] = {\n" + "\n".join(rows) + "\n};\n"
    f"const unsigned vmview_iface_count = {len(rows)};\n")
