# Where things live: sourced by the setup steps and the launchers; sets the VGD_* variables.
# Each one comes from, in this order: the environment, ~/.config/virtio-gpu-desktop/paths.conf
# (VGD_NAME=path lines, ~ and $HOME allowed; another file with VGD_CONFIG=), or the default below.
# The defaults are the layout the project grew up in, which bench/ and the notes still assume.
_vgd_conf=${VGD_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/virtio-gpu-desktop/paths.conf}
if [ -r "$_vgd_conf" ]; then
	while IFS= read -r _vgd_line || [ -n "$_vgd_line" ]; do
		[[ $_vgd_line =~ ^(VGD_[A-Z0-9_]+)=(.*)$ ]] || continue
		_vgd_k=${BASH_REMATCH[1]} _vgd_v=${BASH_REMATCH[2]}
		_vgd_v=${_vgd_v#\"} _vgd_v=${_vgd_v%\"}
		case $_vgd_v in "~"/*) _vgd_v=$HOME/${_vgd_v#"~/"} ;; esac
		_vgd_v=${_vgd_v//'$HOME'/$HOME}
		[ -n "${!_vgd_k+x}" ] || printf -v "$_vgd_k" '%s' "$_vgd_v"
	done < "$_vgd_conf"
fi
unset _vgd_conf _vgd_line _vgd_k _vgd_v
# sources and build trees (rutabaga_gfx, virglrenderer, the guest's RPMs, logs)
: "${VGD_BUILD:=$HOME/build}"
# our QEMU's tree, generated by setup's qemu step from upstream + patches/qemu/series (never edited by
# hand); builds in build-rutabaga (the nested desktop) and build-desktop (main line)
: "${VGD_QEMU_SRC:=$VGD_BUILD/qemu}"
# rutabaga_gfx's FFI library, installed here (QEMU links it; the launcher puts lib64 on the path)
: "${VGD_RUTABAGA_PREFIX:=$VGD_BUILD/rutabaga-prefix}"
# guest disks
: "${VGD_VMS:=$HOME/vms}"
# the nested guest's kernel, initramfs and command line (QEMU boots them directly)
: "${VGD_BOOT:=$HOME/Documents/crosvm-desktop/desktop68/boot}"
# shared with the nested guest: read-only at /mnt/Public (host_share), and the bench results (host_runs)
: "${VGD_SHARE:=$HOME/Documents/crosvm-desktop/desktop68/share}"
: "${VGD_RUNS:=$HOME/Documents/drm-native-context/desktop-bench/runs}"
# the key the guests accept for their user tester
: "${VGD_SSH_KEY:=$HOME/.ssh/vmtest_ed25519}"
# the guest's ssh on the host (127.0.0.1:PORT, the launchers' default; a second VM at the same time
# takes another, through the launcher's own variable)
: "${VGD_SSH_PORT:=2222}"
